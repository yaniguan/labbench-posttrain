"""Compute plate-reader quality from cleaned, real measurements only."""
import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd


def replicate_stats(values):
    values = np.asarray(values, dtype=float)
    values = values[np.isfinite(values)]
    mean = float(values.mean()) if len(values) else None
    sd = float(values.std(ddof=1)) if len(values) >= 2 else None
    cv = 100 * sd / abs(mean) if sd is not None and mean != 0 else None
    return {"n": len(values), "mean": mean, "sample_sd": sd, "cv_percent": cv}


def z_prime(positive, negative):
    p, n = replicate_stats(positive), replicate_stats(negative)
    if p["sample_sd"] is None or n["sample_sd"] is None:
        return None, "Z' needs at least two positive and two negative control wells"
    gap = abs(p["mean"] - n["mean"])
    if gap == 0:
        return None, "control means are equal"
    return 1 - 3 * (p["sample_sd"] + n["sample_sd"]) / gap, None


def quality_report(df):
    plates, replicates = [], []
    d = df[(df.source == "platero_cytation3") & (df.provenance == "measurement")].copy()
    if len(d):
        entities = d.entity.map(json.loads)
        d["plate"] = entities.map(lambda x: x.get("plate"))
        d["label"] = entities.map(lambda x: x.get("well_id"))
        d["control"] = entities.map(lambda x: x.get("control"))
        d["conc_dil"] = d.conditions.map(lambda x: json.loads(x).get("conc_dil"))
        for plate, wells in d.groupby("plate"):
            positive = wells[wells.control == "positive"].value
            negative = wells[wells.control.isin(["negative", "blank"])].value
            z, reason = z_prime(positive, negative)
            plates.append({"source": "platero_cytation3", "plate": plate, "readout": "fluorescence_gain60 (RFU)",
                           "n_wells": len(wells), "n_positive": len(positive), "n_negative_or_blank": len(negative),
                           "z_prime": z, "reason": reason})
        for (plate, label, concentration), group in d.groupby(["plate", "label", "conc_dil"], dropna=False):
            replicates.append({"plate": plate, "well_id": label,
                               "conc_dil": None if pd.isna(concentration) else float(concentration),
                               **replicate_stats(group.value)})
    g = df[df.source == "growth_curves_cytation5"]
    return {"input_records": len(df), "plate_reader_records": len(d) + len(g), "plates": plates,
            "replicate_groups": replicates,
            "notes": [
                "CV = 100 * sample SD / abs(mean), ddof=1; null for n<2 or zero mean. No blank subtraction.",
                "Endpoint replicate candidates share plate, well_id and conc_dil; this is an export-label assumption, not verified biological replication.",
                "SPL1 is a dilution-series sample, not a labeled positive control. No inferred Z' or invented control labels.",
                "Growth curves have H/L labels with unknown meaning and only one BLK; time points are not independent replicates. Growth Z' and replicate CV are not reported.",
                "T3 RM calibration on these metrics remains TODO; these values are not direct RL rewards."]}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--records", default="data/v0/records.parquet")
    parser.add_argument("--out", type=Path, default=Path("outputs/assay_quality.json"))
    parser.add_argument("--doc", type=Path, default=Path("docs/assay_quality.md"))
    args = parser.parse_args()
    report = quality_report(pd.read_parquet(args.records))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    cvs = [r["cv_percent"] for r in report["replicate_groups"] if r["cv_percent"] is not None]
    text = ["# Assay quality from the checked-in plate-reader records", "",
            f"Generated by `scripts/assay_quality.py` from `{args.records}`.", "",
            f"Read {report['plate_reader_records']} plate-reader records. Computed {len(cvs)} endpoint replicate-group CVs.", "",
            "| plate | wells | positive controls | negative/blank controls | Z' |", "|---|---:|---:|---:|---|"]
    for plate in report["plates"]:
        text.append(f"| {plate['plate']} | {plate['n_wells']} | {plate['n_positive']} | {plate['n_negative_or_blank']} | {plate['z_prime'] if plate['z_prime'] is not None else 'unavailable'} |")
    if cvs:
        text += ["", f"Endpoint CV range: {min(cvs):.6g}% to {max(cvs):.6g}%; median {float(np.median(cvs)):.6g}%."]
    text += [""] + report["notes"] + ["", f"Per-group measurements and reasons: `{args.out}`."]
    args.doc.parent.mkdir(parents=True, exist_ok=True)
    args.doc.write_text("\n".join(text) + "\n")
    print(f"wrote {args.out} and {args.doc}")


if __name__ == "__main__":
    main()
