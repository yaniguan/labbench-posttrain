"""Map every catalog row to existing local task interfaces; do not download it."""
import argparse
import csv
import json
from pathlib import Path

import pandas as pd


MODALITIES = {
    "text/protocol": (["reaction", "run_log", "lab_note"], ["protocol2actions", "safety_failure", "provenance"]),
    "robot action/video": (["robot_episode"], ["protocol2actions", "BC", "world_model"]),
    "tabular assay": (["bioassay", "table"], ["outcome", "provenance"]),
    "3D structure/trajectory": (["molecular_property"], ["property_qa", "provenance"]),
    "graph": (["molecular_property"], ["property_qa", "provenance"]),
    "spectra": (["spectrum"], ["spectrum_text alignment", "provenance"]),
    "image": (["image"], ["image denoising"]),
    "time-series instrument log": (["run_log", "table"], ["outcome", "provenance", "masked curve reconstruction"]),
    "multimodal": (["spectrum", "image", "molecular_property"], ["modality/text alignment", "molecule projector"]),
}
LOCAL_FAMILIES = {
    "Open X-Embodiment": ["open_x_embodiment/"], "DROID": ["open_x_embodiment/droid_100"],
    "Open Reaction Database (ORD)": ["ord"], "ChEMBL": ["chembl"],
    "PubChem BioAssay": ["pubchem_bioassay"], "QM9": ["qm9"],
}


def cell(value):
    return str(value).replace("|", " / ").replace("\n", " ")


def build_map(catalog, records, out):
    rows = list(csv.DictReader(open(catalog)))
    needed = {"id", "name", "track_fit", "tasks", "modality", "source", "link", "access", "license", "verified"}
    if not rows or not needed <= rows[0].keys():
        raise ValueError(f"catalog must contain {sorted(needed)}")
    df = pd.read_parquet(records, columns=["source", "modality"])
    lines = ["# Benchmark map", "",
             f"Generated by `scripts/benchmark_link.py` from `{catalog}` and `{records}`: {len(rows)} catalog rows.", "",
             "Track is copied from `track_fit`. Catalog `source` describes evidence origin; it is not our record source identifier.",
             "Local family subset means a small related family sample exists, not that the benchmark evaluation was run. Related sources/tasks are interface matches only; listed benchmarks need their own ingestion, splits, labels and license checks.",
             "BC/world_model require state/action/next_state columns; 3D force/energy, protein, OCSR and QA tasks need new loaders/objectives. No benchmark scores have been measured. GPU results: PENDING (A100 Colab).", "",
             "| id | benchmark | track | catalog task / modality / evidence source | related local sources | local task interface | local status / access / license / link status |",
             "|---|---|---|---|---|---|---|"]
    for row in rows:
        modalities, tasks = MODALITIES.get(row["modality"], ([], []))
        sources = sorted(df[df.modality.isin(modalities)].source.unique())
        prefixes = LOCAL_FAMILIES.get(row["name"], [])
        family = sorted({s for s in df.source.unique() if any(s == p or (p.endswith("/") and s.startswith(p)) for p in prefixes)})
        status = "family subset: " + ", ".join(family) if family else "candidate; not ingested as this benchmark"
        columns = [row["id"], f"[{cell(row['name'])}]({row['link']})", row["track_fit"],
                   f"{row['tasks']} / {row['modality']} / {row['source']}", ", ".join(sources) or "none",
                   ", ".join(tasks) or "TODO: new task", f"{status}; {row['access']}; {row['license']}; {row['verified']}"]
        lines.append("| " + " | ".join(cell(v) for v in columns) + " |")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return len(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=Path("benchmarks/catalog.csv"))
    parser.add_argument("--records", type=Path, default=Path("data/v0/records.parquet"))
    parser.add_argument("--out", type=Path, default=Path("docs/benchmark_map.md"))
    args = parser.parse_args()
    print(f"mapped {build_map(args.catalog, args.records, args.out)} catalog rows to {args.out}")


if __name__ == "__main__":
    main()
